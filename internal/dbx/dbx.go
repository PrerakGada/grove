// Package dbx provisions a worktree's own database.
//
// There is exactly one path to a populated database here, and it proves the
// result. The bash predecessor had two compose generators emitting the same
// container name on the same port — one seeded, one empty — so whichever ran
// last won and the convenient command produced an empty database. That failure
// was silent and cost more debugging time than anything else in the tool.
package dbx

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/PrerakGada/grove/internal/config"
	"github.com/PrerakGada/grove/internal/ui"
)

// ComposeFile is written into each worktree.
const ComposeFile = "docker-compose.grove.yml"

type Env struct {
	Cfg       *config.Config
	MainRoot  string
	Path      string
	Name      string
	Slot      int
	DBName    string
	Container string
	Volume    string
	Port      int
}

// NewEnv resolves the templated database identifiers for one worktree.
func NewEnv(cfg *config.Config, mainRoot, wtPath, name string, slot int) (*Env, error) {
	if !cfg.HasDB() {
		return nil, fmt.Errorf("this project has no database configured in %s", config.FileName)
	}
	v := config.NewVars(cfg, name, mainRoot, wtPath, slot)
	get := func(k string) string { return v[k] }
	return &Env{
		Cfg: cfg, MainRoot: mainRoot, Path: wtPath, Name: name, Slot: slot,
		DBName:    get("db.name"),
		Container: get("db.container"),
		Volume:    get("db.volume"),
		Port:      cfg.DB.Band + slot,
	}, nil
}

// WriteCompose emits the worktree's single compose file.
func (e *Env) WriteCompose() error {
	db := e.Cfg.DB
	body := fmt.Sprintf(`# Generated by grove — isolated database for worktree %q (slot %d).
# Managed by:  grove db %s [%s]
services:
  postgres:
    image: %s
    container_name: %s
    environment:
      POSTGRES_DB: %s
      POSTGRES_USER: %s
      POSTGRES_PASSWORD: %s
    ports:
      - "%d:5432"
    volumes:
      - %s:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U %s -d %s"]
      interval: 5s
      timeout: 5s
      retries: 5

volumes:
  %s:
    name: %s
`, e.Name, e.Slot, e.Name, strings.Join(e.Profiles(), "|"),
		db.Image, e.Container, e.DBName, db.User, db.Password,
		e.Port, e.Volume, db.User, e.DBName, e.Volume, e.Volume)

	return os.WriteFile(filepath.Join(e.Path, ComposeFile), []byte(body), 0o644)
}

// Profiles lists the configured profile names, sorted with the default first.
func (e *Env) Profiles() []string {
	var out []string
	for k := range e.Cfg.DB.Profiles {
		if k != e.Cfg.DB.Default {
			out = append(out, k)
		}
	}
	if e.Cfg.DB.Default != "" {
		out = append([]string{e.Cfg.DB.Default}, out...)
	}
	return out
}

func (e *Env) compose(args ...string) *exec.Cmd {
	full := append([]string{"compose", "-f", ComposeFile}, args...)
	c := exec.Command("docker", full...)
	c.Dir = e.Path
	return c
}

// Up starts the container.
func (e *Env) Up() error {
	c := e.compose("up", "-d")
	if out, err := c.CombinedOutput(); err != nil {
		return fmt.Errorf("could not start the database container: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

// Stop stops the container without deleting its volume.
func (e *Env) Stop() error { return e.compose("stop").Run() }

// Destroy removes the container and its data.
func (e *Env) Destroy() {
	_ = exec.Command("docker", "rm", "-f", e.Container).Run()
	_ = exec.Command("docker", "volume", "rm", "-f", e.Volume).Run()
}

// VolumeExists reports whether this worktree's data volume is already present,
// which is how a first provision is told apart from a restart.
func (e *Env) VolumeExists() bool {
	return exec.Command("docker", "volume", "inspect", e.Volume).Run() == nil
}

// WaitReady blocks until Postgres accepts connections.
func (e *Env) WaitReady(timeout time.Duration) error {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		c := exec.Command("docker", "exec", e.Container,
			"pg_isready", "-U", e.Cfg.DB.User, "-d", "postgres")
		if c.Run() == nil {
			return nil
		}
		time.Sleep(time.Second)
	}
	return fmt.Errorf("postgres in %q did not become ready in %s", e.Container, timeout)
}

// EnsureDump returns the path to a profile's dump, creating it once if missing.
// The first worktree to ask for a profile pays for it; every later one reuses
// the file.
func (e *Env) EnsureDump(profile string) (string, error) {
	dump := filepath.Join(e.MainRoot, e.Cfg.DB.DumpDir, profile+".sql")
	if fi, err := os.Stat(dump); err == nil && fi.Size() > 0 {
		return dump, nil
	}
	cmdline, ok := e.Cfg.DB.Profiles[profile]
	if !ok {
		return "", fmt.Errorf("no command configured for profile %q — "+
			"add it to db.profiles in %s, or use --empty", profile, config.FileName)
	}

	ui.Warn("no cached %s dump yet — creating it once via: %s", profile, cmdline)
	ui.Info("every future worktree reuses %s", dump)
	if err := os.MkdirAll(filepath.Dir(dump), 0o755); err != nil {
		return "", err
	}
	c := exec.Command("/bin/sh", "-c", cmdline)
	c.Dir = e.MainRoot
	c.Stdout, c.Stderr = os.Stderr, os.Stderr
	if err := c.Run(); err != nil {
		return "", fmt.Errorf("%q failed — could not create %s", cmdline, dump)
	}
	if fi, err := os.Stat(dump); err != nil || fi.Size() == 0 {
		return "", fmt.Errorf("%q finished but %s is still missing or empty", cmdline, dump)
	}
	return dump, nil
}

// Restore creates the database if needed and loads a dump into it.
func (e *Env) Restore(dump string) error {
	exists := exec.Command("docker", "exec", e.Container,
		"psql", "-U", e.Cfg.DB.User, "-d", "postgres", "-qAtc",
		"SELECT 1 FROM pg_database WHERE datname='"+e.DBName+"'")
	out, _ := exists.Output()
	if strings.TrimSpace(string(out)) != "1" {
		create := exec.Command("docker", "exec", e.Container,
			"psql", "-U", e.Cfg.DB.User, "-d", "postgres", "-qc",
			"CREATE DATABASE "+e.DBName+" OWNER "+e.Cfg.DB.User+";")
		if o, err := create.CombinedOutput(); err != nil {
			return fmt.Errorf("could not create %s: %s", e.DBName, strings.TrimSpace(string(o)))
		}
	}

	f, err := os.Open(dump)
	if err != nil {
		return err
	}
	defer f.Close()

	// ON_ERROR_STOP is deliberately off: a plain dump routinely reports
	// benign errors (roles that already exist, extensions). The verification
	// below is what decides whether the restore actually worked.
	c := exec.Command("docker", "exec", "-i", e.Container,
		"psql", "-U", e.Cfg.DB.User, "-d", e.DBName, "-v", "ON_ERROR_STOP=0", "-q")
	c.Stdin = f
	if err := c.Run(); err != nil {
		ui.Warn("psql reported errors during restore — verifying the result anyway")
	}
	return nil
}

// Migrate applies pending migrations against this worktree's database.
func (e *Env) Migrate() error {
	if e.Cfg.DB.Migrate == "" {
		return nil
	}
	dir := filepath.Join(e.Path, e.Cfg.DB.MigrateDir)
	c := exec.Command("/bin/sh", "-c", e.Cfg.DB.Migrate)
	c.Dir = dir
	c.Env = append(os.Environ(), "DATABASE_URL="+e.URL())
	if out, err := c.CombinedOutput(); err != nil {
		ui.Warn("migrations reported an issue — the restored data is still usable")
		ui.Warn("%s", firstLines(string(out), 3))
	}
	return nil
}

// URL is the connection string for this worktree's database.
func (e *Env) URL() string {
	return fmt.Sprintf("postgresql://%s:%s@localhost:%d/%s?sslmode=disable",
		e.Cfg.DB.User, e.Cfg.DB.Password, e.Port, e.DBName)
}

// AssertPopulated proves the database actually holds data, and fails loudly
// otherwise. A silently-empty database was the single most common worktree
// failure; it is a hard error now.
func (e *Env) AssertPopulated(profile string) error {
	_ = e.psql("ANALYZE;")

	tables := atoi(e.psql(
		"SELECT count(*) FROM information_schema.tables WHERE table_schema='public';"))
	rows := atoi(e.psql(
		"SELECT COALESCE(SUM(n_live_tup),0)::bigint FROM pg_stat_user_tables;"))

	v := e.Cfg.DB.Verify
	if tables < v.MinTables {
		return fmt.Errorf("restore verification FAILED: only %d table(s) in %s, expected at least %d.\n"+
			"  The %s dump did not apply. Retry with: grove db %s %s --reseed",
			tables, e.DBName, v.MinTables, profile, e.Name, profile)
	}
	if rows < v.MinRows {
		return fmt.Errorf("restore verification FAILED: %d tables but %d row(s) in %s.\n"+
			"  The schema applied but the data did not. Retry with: grove db %s %s --reseed",
			tables, rows, e.DBName, e.Name, profile)
	}
	ui.Ok("verified: %d tables, ~%d rows", tables, rows)
	return nil
}

func (e *Env) psql(q string) string {
	out, err := exec.Command("docker", "exec", e.Container,
		"psql", "-U", e.Cfg.DB.User, "-d", e.DBName, "-qAtc", q).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

func atoi(s string) int {
	n, err := strconv.Atoi(strings.TrimSpace(s))
	if err != nil {
		return 0
	}
	return n
}

func firstLines(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}
